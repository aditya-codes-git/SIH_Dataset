/**
 * AI Agent Assistant Service
 *
 * CRITICAL SAFETY BOUNDARY:
 * - The AI Assistant is NOT the DR prediction model.
 * - It receives ONLY authoritative MATLAB outputs and stored application context.
 * - It DOES NOT evaluate retinal images directly or generate independent medical diagnoses.
 * - It DOES NOT alter or override MATLAB grades, confidence scores, or referral decisions.
 */

const DR_GRADE_DESCRIPTIONS = {
  0: 'Grade 0 - No Apparent Diabetic Retinopathy (No lesions detected).',
  1: 'Grade 1 - Mild Non-Proliferative Diabetic Retinopathy (Microaneurysms only).',
  2: 'Grade 2 - Moderate Non-Proliferative Diabetic Retinopathy (More than microaneurysms, less than severe).',
  3: 'Grade 3 - Severe Non-Proliferative Diabetic Retinopathy (Cotton wool spots, venous beading, severe intraretinal microvascular abnormalities).',
  4: 'Grade 4 - Proliferative Diabetic Retinopathy (Neovascularization, vitreous hemorrhage).',
};

class AIAgentService {
  /**
   * Generates a clear, non-diagnostic explanation of a MATLAB screening result.
   *
   * @param {Object} screening Screening record containing authoritative MATLAB fields
   * @returns {Object} Structured explanation response
   */
  explainScreening(screening) {
    if (!screening) {
      return {
        type: 'EXPLANATION',
        authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
        explanation: "No screening record data provided. I don't have enough information to explain this screening.",
      };
    }

    if (screening.status === 'UNGRADABLE') {
      return {
        type: 'EXPLANATION',
        authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
        status: 'UNGRADABLE',
        explanation: `The MATLAB screening pipeline marked this image as UNGRADABLE. ` +
                     `Reason provided by Image Quality Assessment: "${screening.quality?.reason || 'Suboptimal image quality'}". ` +
                     `Clinical Guidance: ${screening.message || 'Please recapture the retinal image ensuring proper focus, illumination, and field of view.'}`,
        disclaimer: 'This explanation is generated by the AI Assistant based strictly on MATLAB Image Quality Assessment output.',
      };
    }

    const confidencePct = screening.confidence != null ? (screening.confidence * 100).toFixed(2) + '%' : 'N/A';
    const gradeDesc = DR_GRADE_DESCRIPTIONS[screening.drGrade] || `Grade ${screening.drGrade}`;

    const summaryParts = [
      `The MATLAB screening model classified this retinal image as ${gradeDesc} with ${confidencePct} model confidence.`,
      `Referral Status: ${screening.referral || (screening.referable ? 'REFERABLE DR' : 'NON-REFERABLE DR')}.`,
      `Image Quality Assessment passed: Focus score (${screening.quality?.focusScore?.toFixed(6) || 'OK'}), Brightness (${screening.quality?.brightness?.toFixed(4) || 'OK'}), Retinal Field of View (${(screening.quality?.fovRatio * 100)?.toFixed(1) || 'OK'}%).`,
    ];

    if (screening.referable) {
      summaryParts.push(
        `Clinical Recommendation: Because this screening is marked Grade ${screening.drGrade} (≥ Grade 2), a referral for full ophthalmic evaluation is recommended.`
      );
    } else {
      summaryParts.push(
        `Clinical Recommendation: Screening marked Non-Referable DR (< Grade 2). Regular routine monitoring per clinical guidelines is indicated.`
      );
    }

    return {
      type: 'EXPLANATION',
      authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
      status: screening.status,
      screeningId: screening.screeningId,
      patientId: screening.patientId,
      modelOutputSummary: {
        drGrade: screening.drGrade,
        confidence: screening.confidence,
        confidenceFormatted: confidencePct,
        referable: screening.referable,
        referral: screening.referral,
      },
      explanation: summaryParts.join(' '),
      disclaimer: 'The DR classification and referral decisions are generated strictly by the MATLAB AI model. The AI Assistant provides explanatory summaries only.',
    };
  }

  /**
   * Handles user chat queries regarding screening history, quality, or referral details.
   *
   * @param {string} prompt Question asked by user
   * @param {Object} context Context object containing screening data or patient history
   * @returns {Object} Structured chat response
   */
  chatWithAgent(prompt, context = {}) {
    const query = (prompt || '').toLowerCase();
    const screening = context.screening;

    if (!screening) {
      return {
        reply: "I don't have enough screening context to answer that question. Please select a specific patient screening record.",
        authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
      };
    }

    // 1. Referral query
    if (query.includes('refer') || query.includes('why')) {
      if (screening.status === 'UNGRADABLE') {
        return {
          reply: `This screening was not referred for DR grade because the image was UNGRADABLE (${screening.quality?.reason || 'Image quality check failed'}). A image recapture is required.`,
          authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
        };
      }

      if (screening.referable) {
        return {
          reply: `The MATLAB model marked this screening as REFERABLE DR because the assigned grade is Grade ${screening.drGrade} (Confidence: ${(screening.confidence * 100).toFixed(2)}%). Under standard protocol, Grade 2 or higher requires referral to an ophthalmologist for comprehensive examination.`,
          authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
        };
      } else {
        return {
          reply: `This screening was classified as NON-REFERABLE DR by the MATLAB model (Grade ${screening.drGrade}, Confidence: ${(screening.confidence * 100).toFixed(2)}%). Grade 0 and Grade 1 are non-referable per standard screening protocol.`,
          authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
        };
      }
    }

    // 2. Image quality query
    if (query.includes('quality') || query.includes('focus') || query.includes('bright')) {
      const q = screening.quality || {};
      return {
        reply: `Image Quality Assessment Details from MATLAB:\n` +
               `- Gradable: ${q.gradable ? 'YES' : 'NO'}\n` +
               `- Focus Variance Score: ${q.focusScore?.toFixed(6) || 'N/A'} (Threshold >= 0.00008)\n` +
               `- Mean Brightness: ${q.brightness?.toFixed(4) || 'N/A'} (Acceptable range 0.08 - 0.40)\n` +
               `- Field of View Ratio: ${(q.fovRatio * 100)?.toFixed(1) || 'N/A'}% (Threshold >= 45%)\n` +
               `- Result Reason: ${q.reason || 'N/A'}`,
        authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
      };
    }

    // 3. Grade / Diagnosis query
    if (query.includes('grade') || query.includes('diagnosis') || query.includes('result')) {
      if (screening.status === 'UNGRADABLE') {
        return {
          reply: `The MATLAB model status for this screening is UNGRADABLE. No DR grade was calculated due to quality check failure: "${screening.quality?.reason}".`,
          authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
        };
      }
      return {
        reply: `The authoritative MATLAB AI model assigned Grade ${screening.drGrade} (${DR_GRADE_DESCRIPTIONS[screening.drGrade]}) with ${(screening.confidence * 100).toFixed(2)}% confidence.`,
        authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
      };
    }

    // Fallback general response strictly summarizing existing fields
    return {
      reply: `For screening ${screening.screeningId} (Patient: ${screening.patientId || 'Anonymous'}):\n` +
             `- Status: ${screening.status}\n` +
             `- Grade: ${screening.drGrade ?? 'N/A'}\n` +
             `- Confidence: ${screening.confidence != null ? (screening.confidence * 100).toFixed(2) + '%' : 'N/A'}\n` +
             `- Referral: ${screening.referral || 'N/A'}\n` +
             `Note: As an AI assistant, I only explain official MATLAB model outputs and cannot provide an independent medical diagnosis.`,
      authoritativeModelUsed: 'MATLAB DR AI Pipeline (drScreen.m)',
    };
  }
}

module.exports = new AIAgentService();
