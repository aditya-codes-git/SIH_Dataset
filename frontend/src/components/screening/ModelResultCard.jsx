import React from 'react';
import { ShieldCheck, AlertCircle, CheckCircle, Percent } from 'lucide-react';
import { Card } from '../ui/Card';
import { Badge } from '../ui/Badge';

const GRADE_LABELS = {
  0: 'Grade 0 — No Apparent DR',
  1: 'Grade 1 — Mild Non-Proliferative DR',
  2: 'Grade 2 — Moderate Non-Proliferative DR',
  3: 'Grade 3 — Severe Non-Proliferative DR',
  4: 'Grade 4 — Proliferative DR',
};

export const ModelResultCard = ({ result }) => {
  if (!result || result.status === 'UNGRADABLE') return null;

  const grade = result.drGrade ?? result.grade ?? 0;
  const confidence = result.confidence != null ? (result.confidence * 100).toFixed(2) : '0';
  const isReferable = result.referable;
  const referralText = result.referral || (isReferable ? 'REFERABLE DR' : 'NON-REFERABLE DR');

  return (
    <Card
      title="MATLAB MODEL RESULT"
      subtitle="Generated by the validated project screening pipeline (drScreen.m)"
      action={
        <Badge variant={isReferable ? 'danger' : 'success'} size="lg">
          {referralText}
        </Badge>
      }
      style={{
        borderTop: `4px solid ${isReferable ? 'var(--danger)' : 'var(--success)'}`,
      }}
    >
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))', gap: '1.25rem', margin: '1rem 0' }}>
        {/* DR Grade Box */}
        <div style={{
          padding: '1.25rem',
          borderRadius: 'var(--radius-md)',
          backgroundColor: isReferable ? 'var(--danger-bg)' : 'var(--success-bg)',
          border: `1px solid ${isReferable ? 'rgba(239, 68, 68, 0.2)' : 'rgba(16, 185, 129, 0.2)'}`,
        }}>
          <span style={{ fontSize: '0.75rem', fontWeight: 600, color: 'var(--text-secondary)', textTransform: 'uppercase' }}>
            Predicted DR Grade
          </span>
          <div style={{ display: 'flex', alignItems: 'baseline', gap: '0.5rem', marginTop: '0.25rem' }}>
            <span style={{ fontSize: '2.25rem', fontWeight: 800, color: isReferable ? 'var(--danger)' : 'var(--success)' }}>
              Grade {grade}
            </span>
          </div>
          <p style={{ fontSize: '0.8125rem', fontWeight: 500, color: 'var(--text-primary)', marginTop: '0.25rem', margin: 0 }}>
            {GRADE_LABELS[grade] || `Grade ${grade}`}
          </p>
        </div>

        {/* Model Confidence Box */}
        <div style={{
          padding: '1.25rem',
          borderRadius: 'var(--radius-md)',
          backgroundColor: 'var(--bg-secondary)',
          border: '1px solid var(--border-color)',
        }}>
          <span style={{ fontSize: '0.75rem', fontWeight: 600, color: 'var(--text-secondary)', textTransform: 'uppercase' }}>
            Model Confidence
          </span>
          <div style={{ display: 'flex', alignItems: 'baseline', gap: '0.25rem', marginTop: '0.25rem' }}>
            <span style={{ fontSize: '2.25rem', fontWeight: 800, color: 'var(--text-primary)' }}>
              {confidence}%
            </span>
          </div>
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.375rem', marginTop: '0.375rem', fontSize: '0.75rem', color: 'var(--text-secondary)' }}>
            <Percent size={14} color="var(--primary)" />
            <span>Raw Output: {result.confidence}</span>
          </div>
        </div>

        {/* Referral Protocol Box */}
        <div style={{
          padding: '1.25rem',
          borderRadius: 'var(--radius-md)',
          backgroundColor: 'var(--bg-secondary)',
          border: '1px solid var(--border-color)',
        }}>
          <span style={{ fontSize: '0.75rem', fontWeight: 600, color: 'var(--text-secondary)', textTransform: 'uppercase' }}>
            Referral Decision
          </span>
          <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', marginTop: '0.5rem' }}>
            {isReferable ? <AlertCircle size={20} color="var(--danger)" /> : <CheckCircle size={20} color="var(--success)" />}
            <span style={{ fontSize: '1rem', fontWeight: 700, color: isReferable ? 'var(--danger)' : 'var(--success)' }}>
              {isReferable ? 'Ophthalmic Referral Needed' : 'No Referral Needed'}
            </span>
          </div>
          <p style={{ fontSize: '0.75rem', color: 'var(--text-secondary)', marginTop: '0.375rem', margin: 0 }}>
            {isReferable ? 'Grade ≥ 2 threshold met per protocol.' : 'Grade < 2 non-referable threshold.'}
          </p>
        </div>
      </div>

      <div style={{
        display: 'flex',
        alignItems: 'center',
        gap: '0.5rem',
        fontSize: '0.75rem',
        color: 'var(--text-muted)',
        borderTop: '1px solid var(--border-color)',
        paddingTop: '0.75rem',
        marginTop: '0.5rem',
      }}>
        <ShieldCheck size={14} color="var(--primary)" />
        <span>Prototype validation on the current APTOS validation split. All values received directly from MATLAB black-box engine.</span>
      </div>
    </Card>
  );
};
